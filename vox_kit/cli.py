def get_config(aspect: str = "9:16", fps: int = 24, duration: float = 4.0) -> VideoConfig:
    return VideoConfig.from_aspect(aspect=aspect, fps=fps, duration=duration)


def build_audio(wav_path: Path, config: VideoConfig) -> Path:
    mixer = SoundMixer(duration=config.duration, seed=42)
    mixer.add_editorial_bed(bpm=108, gain=0.14)
    mixer.add_sfx(0.15, "slap", amp=0.9)
    mixer.add_sfx(1.40, "stamp_thud", amp=1.0)
    return mixer.export_wav(wav_path)


def init_worker(cfg_dict: dict) -> None:
    w, h, fps = cfg_dict["width"], cfg_dict["height"], cfg_dict["fps"]
    STATE["w"], STATE["h"], STATE["fps"] = w, h, fps
    STATE["board"] = build_cream_board(w, h)
    STATE["tex"], STATE["dusts"] = build_paper_overlay(w, h, seed=42)
    STATE["title"] = make_torn_strip("VOX EDITORIAL DEMO", bg=C_INK, fg=C_YELLOW, font_size=56, seed=11)
    STATE["stamp"] = make_red_stamp_on_slip("VERIFIED!", font_size=74, seed=21, with_slip=True)
    STATE["icon"] = make_procedural_halftone_icon("coffee_cup", size=280, accent=C_YELLOW, seed=7)
    STATE["subs"] = captions_to_groups(
        [
            TimedCaption(0.1, 1.9, "Deterministic paper collage."),
            TimedCaption(2.0, 3.8, "Ready for 9:16 and 16:9."),
        ],
        duration=cfg_dict["duration"],
    )


def render_frame(f: int) -> bytes:
    w, h, fps = STATE["w"], STATE["h"], STATE["fps"]
    t = f / fps
    frame = STATE["board"].convert("RGBA")
    composite_smooth(frame, STATE["title"], w * 0.5, h * 0.24, f, 0, int(fps * 4.5), fps=fps, rot=-0.8)
    composite_smooth(frame, STATE["icon"], w * 0.5, h * 0.48, f, 4, int(fps * 4.5), fps=fps, float_amp=4.0)
    composite_smooth(frame, STATE["stamp"], w * 0.5, h * 0.68, f, int(fps * 1.4), int(fps * 4.5), fps=fps, rot=-2.5, stamp_pop=True)
    draw_subtitle_bar(frame, t, STATE["subs"], w, h)
    return apply_paper_overlay(frame, STATE["tex"], STATE["dusts"], f).tobytes()



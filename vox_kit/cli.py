def _clean_path(raw: str, *, reject_parent_traversal: bool = False) -> Path:
    if "\x00" in raw:
        raise ValueError("Path contains null byte")
    p = Path(raw)
    if reject_parent_traversal and ".." in p.parts:
        raise ValueError(f"Path traversal ('..') is not allowed: {raw!r}")
    return p.expanduser().resolve()


def _cmd_map_prep(args: argparse.Namespace) -> int:
    geojson = _clean_path(args.geojson) if args.geojson else (get_assets_dir() / "data" / "countries_50m.geojson")
    if not geojson.is_file():
        print(f"ERROR: GeoJSON file not found: {geojson}", file=sys.stderr)
        return 1

    countries: List[str] = []
    for tok in args.countries.split(","):
        tok = tok.strip()
        if not tok:
            continue
        if not _SAFE_CODE_RE.match(tok):
            print(f"ERROR: Invalid country code: {tok!r}", file=sys.stderr)
            return 1
        countries.append(tok.upper())

    proj = None
    if args.bbox:
        parts = [float(x.strip()) for x in args.bbox.split(",")]
        if len(parts) != 4:
            print("ERROR: --bbox must be 'lon_min,lon_max,lat_min,lat_max'", file=sys.stderr)
            return 1
        proj = MapProjection(
            lon_min=parts[0],
            lon_max=parts[1],
            lat_min=parts[2],
            lat_max=parts[3],
            map_w=args.map_w,
        )
    else:
        proj = MapProjection(map_w=args.map_w)

    out_dir = _clean_path(args.out)
    meta = build_map_cache(geojson, out_dir, countries=countries, projection=proj)
    print(f"Map cache ready in {out_dir} ({meta['projection']['map_w']}x{meta['projection']['map_h']}, countries={meta['countries']})")
    return 0


def _load_scene_module(script_path: Path):
    spec = importlib.util.spec_from_file_location("vox_user_scene", str(script_path))
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Unable to load scene script: {script_path}")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


def _cmd_render(args: argparse.Namespace) -> int:
    script = _clean_path(args.scene)
    if not script.is_file():
        print(f"ERROR: Scene script not found: {script}", file=sys.stderr)
        return 1
    if script.suffix.lower() != ".py":
        print(f"ERROR: Scene script must be a .py file: {script}", file=sys.stderr)
        return 1
    out_mp4 = _clean_path(args.out)
    mod = _load_scene_module(script)

    if hasattr(mod, "render_to_file"):
        kwargs = {
            "aspect": args.aspect,
            "fps": args.fps,
            "workers": args.workers,
            "normalize": not args.no_normalize,
        }
        mod.render_to_file(out_mp4, **kwargs)
    elif hasattr(mod, "render_frame"):
        if hasattr(mod, "get_config"):
            cfg = mod.get_config(aspect=args.aspect, fps=args.fps)
        elif hasattr(mod, "CONFIG"):
            cfg = mod.CONFIG
        else:
            cfg = VideoConfig.from_aspect(aspect=args.aspect, fps=args.fps, duration=args.duration or 10.0)
        if args.workers is not None or args.duration is not None:
            cfg = VideoConfig(
                width=cfg.width,
                height=cfg.height,
                fps=cfg.fps,
                duration=args.duration if args.duration is not None else cfg.duration,
                workers=args.workers if args.workers is not None else cfg.workers,
                crf=cfg.crf,
                preset=cfg.preset,
            )
        init_fn = getattr(mod, "init_worker", None)
        init_args = getattr(mod, "get_init_args", lambda c: {"width": c.width, "height": c.height, "fps": c.fps, "duration": c.duration})(cfg)
        with tempfile.TemporaryDirectory(prefix="vox_cli_") as td:
            audio_wav = None
            if hasattr(mod, "build_audio"):
                audio_wav = Path(td) / "mix.wav"
                mod.build_audio(audio_wav, cfg)
            render_scene(
                cfg,
                init_fn,
                init_args,
                mod.render_frame,
                audio_wav,
                out_mp4,
                normalize=not args.no_normalize,
            )
    else:
        print("ERROR: Scene script must define `render_to_file(...)` or `render_frame(f)`.", file=sys.stderr)
        return 1

    print(f"Rendered: {out_mp4}")
    return 0


def _cmd_check(args: argparse.Namespace) -> int:
    video = _clean_path(args.video)
    report = check_video(video, lufs_min=args.lufs_min, lufs_max=args.lufs_max)
    if args.json:
        print(json.dumps(report, indent=2))
    else:
        status = "OK" if report["ok"] else "FAILED"
        print(
            f"[{status}] {report['path']} | {report['width']}x{report['height']} @ {report['fps']} fps | "
            f"frames={report['total_frames']} | broken={len(report['broken_frames'])} | "
            f"lufs={report['lufs']} dB (peak {report['true_peak_dbtp']} dBTP)"
        )
        for bf in report["broken_frames"]:
            print(f"  broken frame {bf['frame']} ({bf['time_s']}s): prev={bf['diff_prev']} next={bf['diff_next']} nbr={bf['diff_neighbors']}")
        for err in report["errors"]:
            print(f"  ERROR: {err}", file=sys.stderr)
    return 0 if report["ok"] else 2


def _cmd_contact_sheet(args: argparse.Namespace) -> int:
    if not _SAFE_GRID_RE.match(args.grid):
        print(f"ERROR: Invalid grid {args.grid!r}; expected e.g. '8x2'", file=sys.stderr)
        return 1
    video = _clean_path(args.video)
    out_dir = _clean_path(args.out)
    sheets = make_contact_sheet(video, out_dir, fps=args.fps, grid=args.grid, tile_width=args.tile_width)
    print(f"Generated {len(sheets)} contact sheet(s) in {out_dir}")
    for s in sheets:
        print(f"  {s}")
    return 0


def _cmd_init(args: argparse.Namespace) -> int:
    dest = _clean_path(args.dest, reject_parent_traversal=True)
    dest.mkdir(parents=True, exist_ok=True)
    scene_file = dest / "scene.py"
    if scene_file.exists() and not args.force:
        print(f"ERROR: {scene_file} already exists (use --force to overwrite)", file=sys.stderr)
        return 1
    scene_file.write_text(_STARTER_SCENE, encoding="utf-8")
    print(f"Initialized starter scene: {scene_file}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="vox-kit",
        description="Sphyrex Hybrid Vox x Engraving deterministic editorial video toolkit.",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    p_map = sub.add_parser("map-prep", help="Build Natural Earth engraved map mipmaps and country masks")
    p_map.add_argument("--geojson", default=None, help="Path to countries_50m.geojson (defaults to bundled asset)")
    p_map.add_argument("--countries", default="BRA,COL,TUR", help="Comma-separated ISO_A3/ADM0_A3 country codes")
    p_map.add_argument("--out", required=True, help="Output directory for mipmaps and masks")
    p_map.add_argument("--bbox", default=None, help="Optional lon_min,lon_max,lat_min,lat_max")
    p_map.add_argument("--map-w", type=int, default=5400, help="Base map width in pixels (default: 5400)")
    p_map.set_defaults(func=_cmd_map_prep)

    p_ren = sub.add_parser("render", help="Render a Vox scene Python script to MP4")
    p_ren.add_argument("scene", help="Path to scene.py script")
    p_ren.add_argument("--out", required=True, help="Output MP4 path")
    p_ren.add_argument("--aspect", default="9:16", choices=["9:16", "16:9", "1:1", "4:5"], help="Target aspect ratio")
    p_ren.add_argument("--fps", type=int, default=24, help="Frame rate (24 default for AI clip lock)")
    p_ren.add_argument("--duration", type=float, default=None, help="Override duration in seconds")
    p_ren.add_argument("--workers", type=int, default=None, help="Number of worker processes")
    p_ren.add_argument("--no-normalize", action="store_true", help="Skip 2-pass -14 LUFS loudnorm")
    p_ren.set_defaults(func=_cmd_render)

    p_chk = sub.add_parser("check", help="Scan MP4 for single-frame glitches and verify -16..-12 LUFS")
    p_chk.add_argument("video", help="Path to MP4 file")
    p_chk.add_argument("--lufs-min", type=float, default=-16.0, help="Minimum allowed LUFS (default: -16)")
    p_chk.add_argument("--lufs-max", type=float, default=-12.0, help="Maximum allowed LUFS (default: -12)")
    p_chk.add_argument("--json", action="store_true", help="Print full JSON QA report")
    p_chk.set_defaults(func=_cmd_check)

    p_cs = sub.add_parser("contact-sheet", help="Generate tiled JPEG contact sheets from an MP4")
    p_cs.add_argument("video", help="Path to MP4 file")
    p_cs.add_argument("--out", required=True, help="Output directory for sheet_XX.jpg")
    p_cs.add_argument("--fps", type=float, default=1.0, help="Frames per second sampled (default: 1.0)")
    p_cs.add_argument("--grid", default="8x2", help="Tile grid colsxrows (default: 8x2)")
    p_cs.add_argument("--tile-width", type=int, default=270, help="Width of each tile in pixels")
    p_cs.set_defaults(func=_cmd_contact_sheet)

    p_init = sub.add_parser("init", help="Create a starter Vox scene project")
    p_init.add_argument("dest", help="Destination directory for starter scene.py")
    p_init.add_argument("--force", action="store_true", help="Overwrite existing scene.py")
    p_init.set_defaults(func=_cmd_init)

    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        return int(args.func(args))
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
